program gen_qed
    ! Closed forms of tree-level QED for the P1g kernels: spin-averaged squared
    ! matrix elements in Mandelstam invariants with e^4 divided out, and cross
    ! sections in units of r_e^2. src/quantum/qed_tree.f90 evaluates the same
    ! processes from the Feynman rules; the two are each other's oracle.
    use fortsym_expr, only: expr_t, sym, num, pi_expr, sqrt, log, cos, &
                            operator(+), operator(-), operator(*), operator(/), &
                            operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    use fortsym_engine, only: engine_result_t
    use fortsym_string, only: chars
    implicit none
    ! Taylor order of the low-energy Klein-Nishina branch, used for x < 0.2:
    ! the series converges for |x| < 1/2 (log(1+2x)), so its terms fall
    ! like 0.4^n there; the closed form loses about eps/x^3 below
    integer, parameter :: KN_ORDER = 48
    type(engine_result_t) :: series
    type(leaf_writer_t) :: w
    type(expr_t) :: s, t, u, m, m2, a, b, c, pk, pkp, x, r, cosine, beta, gamma, theta, z
    type(expr_t) :: half_sin2, root

    s = sym('s'); t = sym('t'); u = sym('u'); m = sym('m')
    m2 = m**2
    call w%open('gen_qed', 'src/generated/milca_qed_leaves.f90')
    call w%line('! Generated by gen/gen_qed.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Tree-level QED, metric (+,-,-,-), s+t+u = sum of squared masses.')
    call w%line('! *_msq: (1/4) sum over all spins and polarizations of |M|^2 / e^4.')
    call w%line('! Cross sections in units of r_e^2 = (alpha hbar/(m c))^2.')
    call w%line('module milca_qed_leaves')
    call w%line('implicit none')
    call w%line('contains')

    ! Moller e-e- -> e-e-: t and u exchange with the fermion sign
    ! (Berestetskii, Lifshitz and Pitaevskii, section 81)
    a = s - 2*m2
    call w%emit('qed_moller_msq', ['s', 't', 'u', 'm'], ['msq'], &
        [2*(((a**2 + (u - 2*m2)**2 + 4*m2*t)/t**2) + &
            ((a**2 + (t - 2*m2)**2 + 4*m2*u)/u**2) + 2*a*(s - 6*m2)/(t*u))], ad=.true.)
    ! Bhabha e-e+ -> e-e+: Moller crossed s <-> u (section 81)
    a = u - 2*m2
    call w%emit('qed_bhabha_msq', ['s', 't', 'u', 'm'], ['msq'], &
        [2*(((a**2 + (s - 2*m2)**2 + 4*m2*t)/t**2) + &
            ((a**2 + (t - 2*m2)**2 + 4*m2*s)/s**2) + 2*a*(u - 6*m2)/(t*s))], ad=.true.)
    ! Compton e(p) gamma(k) -> e(p') gamma(k'): p.k = (s-m^2)/2, p.k' = (m^2-u)/2
    pk = (s - m2)/2
    pkp = (m2 - u)/2
    call w%emit('qed_compton_msq', ['s', 'u', 'm'], ['msq'], &
        [2*(pkp/pk + pk/pkp + 2*m2*(1/pk - 1/pkp) + m2**2*(1/pk - 1/pkp)**2)], ad=.true.)
    ! annihilation e-(p1) e+(p2) -> gamma(k1) gamma(k2), t = (p1-k1)^2,
    ! u = (p1-k2)^2; by crossing also Breit-Wheeler gamma gamma -> e- e+
    b = (m2 - t)/2
    c = (m2 - u)/2
    call w%emit('qed_annihilation_msq', ['t', 'u', 'm'], ['msq'], &
        [2*(c/b + b/c + 2*m2*(1/b + 1/c) - m2**2*(1/b + 1/c)**2)], ad=.true.)

    ! Mott: electron of speed beta on a static charge Z, centre-of-mass angle
    ! theta of the infinitely heavy nucleus frame (section 80)
    beta = sym('beta'); theta = sym('theta'); z = sym('z')
    half_sin2 = (1 - cos(theta))/2
    call w%emit('qed_mott_dcs', ['beta ', 'theta', 'z    '], ['dcs'], &
        [z**2*(1 - beta**2)*(1 - beta**2*half_sin2)/(4*beta**4*half_sin2**2)], ad=.true.)

    ! Klein-Nishina, electron at rest, x = omega/(m c^2), cosine of the
    ! photon scattering angle; total cross section integrated in closed form
    x = sym('x'); cosine = sym('cosine')
    r = 1/(1 + x*(1 - cosine))
    call w%emit('qed_klein_nishina_dcs', ['x     ', 'cosine'], ['dcs'], &
        [r**2*(r + 1/r - (1 - cosine**2))/2], ad=.true.)
    ! the closed form cancels to O(x^3) inside its first term and loses
    ! about eps/x^3; below x = 0.2 the Taylor series of the same expression
    ! replaces it
    a = (1 + x)/x**3*(2*x*(1 + x)/(1 + 2*x) - log(1 + 2*x)) + &
        log(1 + 2*x)/(2*x) - (1 + 3*x)/(1 + 2*x)**2
    call w%emit('qed_klein_nishina_total', ['x'], ['sigma'], [2*pi_expr()*a], ad=.true.)
    series = w%engine%series(a, x, num(0), KN_ORDER)
    if (.not. series%ok) error stop 'gen_qed: Klein-Nishina series refused: '//chars(series%message)
    call w%emit('qed_klein_nishina_total_low', ['x'], ['sigma'], [2*pi_expr()*series%value], &
        ad=.true.)
    ! Breit-Wheeler total, beta the lepton speed in the centre-of-mass frame
    call w%emit('qed_breit_wheeler_total', ['beta'], ['sigma'], &
        [pi_expr()/2*(1 - beta**2)*((3 - beta**4)*log((1 + beta)/(1 - beta)) - &
            2*beta*(2 - beta**2))], ad=.true.)
    ! Dirac pair annihilation, gamma the positron Lorentz factor with the
    ! electron at rest
    gamma = sym('gamma')
    root = sqrt(gamma**2 - 1)
    call w%emit('qed_dirac_annihilation_total', ['gamma'], ['sigma'], &
        [pi_expr()/(gamma + 1)*((gamma**2 + 4*gamma + 1)/(gamma**2 - 1)*log(gamma + root) - &
            (gamma + 3)/root)], ad=.true.)
    call w%line('end module milca_qed_leaves')
    call w%close()


end program gen_qed
