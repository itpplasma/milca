program gen_fb_gamma_p
   ! Pointwise leaves of the vacuum on the moving plasma boundary Gamma_p
   ! (src/mhd/ideal_fb_gamma_p.f90). At a surface point with tangents
   ! a = dx/du, b = dx/dv, area normal N = a x b (out of the plasma), external
   ! field e = B_ext(x) and potential derivatives pu = dPhi/du, pv = dPhi/dv,
   ! the vacuum field with B.n = 0 is
   !   B = e - (e.N) N/|N|^2 + grad_Gamma Phi,
   !   grad_Gamma Phi = ((b.b pu - a.b pv) a + (a.a pv - a.b pu) b)/|N|^2,
   ! and the Hadamard traction density of E_v (per du dv) is
   !   s = -|B|^2 N/2,  dE_v = int s.dx du dv.
   ! Proved below: B.N = 0, B.a = e.a + pu, B.b = e.b + pv, so B is the
   ! tangential field of the exterior Neumann solution dPhi/dn = -e.n.
   ! gamma_p_traction_jvp is the tangent of s in all eleven arguments (the
   ! vacuum Hessian); with e = 0 gamma_p_field is grad_Gamma of a scalar.
   use fortsym_expr, only: expr_t, sym, num, operator(+), operator(-), &
                           operator(*), operator(/)
   use fortsym_diff, only: diff
   use fortsym_engine, only: engine_result_t, VERDICT_TRUE
   use fortsym_engine_native, only: native_engine_t, make_native_engine
   use milca_gen_support, only: leaf_writer_t, fortsym_revision
   implicit none
   type(leaf_writer_t) :: w
   type(native_engine_t) :: engine
   type(engine_result_t) :: check
   type(expr_t) :: a(3), b(3), e(3), pu, pv, n(3), nn, en, aa, ab, bb
   type(expr_t) :: field(3), scaled(3), traction(3), flux, b2
   character(4), parameter :: args(11) = [character(4) :: 'a1', 'a2', 'a3', &
      'b1', 'b2', 'b3', 'e1', 'e2', 'e3', 'pu', 'pv']
   type(expr_t) :: t, lagrange(0:3), slope(0:3), unity
   character(4) :: names(8)
   character(1) :: suffix
   integer :: i, order, j, k
   engine = make_native_engine()
   do i = 1, 3
      a(i) = sym(trim(args(i))); b(i) = sym(trim(args(i + 3)))
      e(i) = sym(trim(args(i + 6)))
   end do
   pu = sym('pu'); pv = sym('pv')
   n(1) = a(2)*b(3) - a(3)*b(2)
   n(2) = a(3)*b(1) - a(1)*b(3)
   n(3) = a(1)*b(2) - a(2)*b(1)
   nn = dot(n, n); en = dot(e, n)
   aa = dot(a, a); ab = dot(a, b); bb = dot(b, b)
   ! Proofs on the polynomial |N|^2 B; |a x b|^2 = |a|^2 |b|^2 - (a.b)^2
   ! makes grad_Gamma Phi dual to (a, b).
   do i = 1, 3
      scaled(i) = nn*e(i) - en*n(i) + (bb*pu - ab*pv)*a(i) + (aa*pv - ab*pu)*b(i)
      field(i) = scaled(i)/nn
   end do
   call prove(dot(scaled, n), 'normal field')
   call prove(dot(scaled, a) - (dot(e, a) + pu)*nn, 'u component')
   call prove(dot(scaled, b) - (dot(e, b) + pv)*nn, 'v component')
   b2 = dot(field, field)
   do i = 1, 3
      traction(i) = (0 - b2)*n(i)/2
   end do
   flux = en
   call w%open('gen_fb_gamma_p', 'src/generated/milca_fb_gamma_p_leaves.f90')
   call w%line('! Generated by gen/gen_fb_gamma_p.f90; do not edit.')
   call w%line('! FortSym revision: '//fortsym_revision)
   call w%line('! Vacuum field on Gamma_p, B = e - (e.N) N/|N|^2 + grad_Gamma Phi,')
   call w%line('! N = a x b; traction s = -|B|^2 N/2 per du dv; flux e.N per du dv.')
   call w%line('module milca_fb_gamma_p_leaves')
   call w%line('implicit none')
   call w%line('contains')
   call w%emit('gamma_p_field', [character(4) :: args], &
      [character(4) :: 'f1', 'f2', 'f3'], field)
   call w%emit('gamma_p_traction', [character(4) :: args], &
      [character(4) :: 's1', 's2', 's3'], traction, ad=.true.)
   call w%emit('gamma_p_flux', [character(4) :: args(1:9)], ['q'], [flux])
   ! Chain edge bases: Lagrange on the equispaced nodes l/order of [0, 1]
   ! and their t derivatives; partition of unity proved.
   t = sym('t')
   do order = 2, 3
      unity = num(-1)
      do j = 0, order
         lagrange(j) = num(1)
         do k = 0, order
            if (k /= j) lagrange(j) = lagrange(j)*(order*t - k)/(j - k)
         end do
         slope(j) = diff(lagrange(j), t)
         unity = unity + lagrange(j)
      end do
      call prove(unity, 'partition of unity')
      do j = 0, order
         write (names(j + 1), '(a,i1)') 'w', j
         write (names(order + j + 2), '(a,i1)') 'dw', j
      end do
      write (suffix, '(i1)') order
      call w%emit('gamma_p_edge_p'//suffix, ['t'], &
         [character(4) :: names(1:2*order + 2)], [lagrange(0:order), slope(0:order)])
   end do
   call w%line('end module milca_fb_gamma_p_leaves')
   call w%close()
contains
   type(expr_t) function dot(x, y) result(r)
      type(expr_t), intent(in) :: x(3), y(3)
      r = x(1)*y(1) + x(2)*y(2) + x(3)*y(3)
   end function
   subroutine prove(expression, what)
      type(expr_t), intent(in) :: expression
      character(*), intent(in) :: what
      check = engine%zero_test(expression)
      if (check%verdict /= VERDICT_TRUE) then
         write (*, '(a)') 'unproved: '//what
         error stop 1
      end if
   end subroutine
end program gen_fb_gamma_p
