program gen_winslow_seed
    ! Winslow (inverse-harmonic) energy density of a plane map X(y): with
    ! A(k, i) = dX_k/dy_i, w = |A|_F^2 / h(det A), the Dirichlet energy of the
    ! inverse map per reference area. h(d) = (d + sqrt(d^2 + eps^2))/2
    ! regularises the determinant for untangling (Escobar et al., Comput.
    ! Methods Appl. Mech. Engrg. 192, 2775 (2003)); h = d for eps = 0, d > 0.
    ! For d < 0 the sum d + sqrt(d^2 + eps^2) cancels once eps << |d|, so the
    ! folded leaves use the equal form eps^2/(2 (sqrt(d^2 + eps^2) - d)).
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/), operator(**), sqrt
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(engine_result_t) :: proof
    type(expr_t) :: a(4), eps, d, root, h, folded, norm
    character(3), parameter :: names(4) = ['a11', 'a21', 'a12', 'a22']
    integer :: i
    call w%open('gen_winslow_seed', 'src/generated/milca_winslow_seed_leaves.f90')
    call w%line('! Generated by gen/gen_winslow_seed.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module milca_winslow_seed_leaves')
    call w%line('use, intrinsic :: iso_fortran_env, only: dp => real64')
    call w%line('implicit none')
    call w%line('contains')
    do i = 1, 4
        a(i) = sym(names(i))
    end do
    eps = sym('eps')
    ! columns are the reference directions: A = [a11 a12; a21 a22]
    d = a(1)*a(4) - a(3)*a(2)
    root = sqrt(d**2 + eps**2)
    h = (d + root)/2
    folded = eps**2/(2*(root - d))
    engine = make_native_engine()
    proof = engine%zero_test(h*(2*(root - d)) - eps**2)
    if (proof%verdict /= VERDICT_TRUE) error stop 'folded determinant form unproved'
    norm = a(1)**2 + a(2)**2 + a(3)**2 + a(4)**2
    call emit_leaves('winslow', norm/h)
    call emit_leaves('winslow_folded', norm/folded)
    call w%line('end module milca_winslow_seed_leaves')
    call w%close()
    print '(a)', '[V] FortSym folded determinant form proved; Winslow leaves generated'
contains
    subroutine emit_leaves(prefix, density)
        character(*), intent(in) :: prefix
        type(expr_t), intent(in) :: density
        type(expr_t) :: gradient(4), hessian(10)
        character(3) :: gnames(4)
        character(7) :: hnames(10)
        integer :: i, j, k
        do i = 1, 4
            gradient(i) = diff(density, a(i))
            gnames(i) = 'g'//names(i)(2:3)
        end do
        k = 0
        do j = 1, 4
            do i = 1, j
                k = k + 1
                hessian(k) = diff(gradient(i), a(j))
                write (hnames(k), '(a,i0,a,i0)') 'h', i, '_', j
            end do
        end do
        call w%emit(prefix//'_density', [character(3) :: names, 'eps'], ['w  ', 'det'], &
            [density, d])
        call w%emit(prefix//'_gradient', [character(3) :: names, 'eps'], gnames, gradient)
        call w%emit(prefix//'_hessian', [character(3) :: names, 'eps'], hnames, hessian)
    end subroutine
end program
