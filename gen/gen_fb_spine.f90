program gen_fb_spine
    ! Inner node of the layered free-boundary shell (ideal_fb_t spines): the
    ! intersection P = gamma(t) of a fixed spine through o with tangent normal
    ! tau (tau . (P - o) = 0) and the plasma boundary chain, represented by
    ! the uniform Catmull-Rom segment between chain nodes X_1 and X_2,
    ! gamma(t) = sum_l c_l(t) X_l, l = 0..3, t in [0, 1]. It interpolates the
    ! chain nodes and is C1 across them, so P(X) is differentiable also where
    ! a spine meets a chain node (the P3 chain is only C0 at its vertices).
    ! t(X) is implicit in f(t, X) = tau . (gamma(t) - o) = 0:
    !   dt_a = -f_a/f_t,
    !   d2t_ab = -(f_tt dt_a dt_b + f_ta dt_b + f_tb dt_a)/f_t   (f_ab = 0),
    ! and P(X) = gamma(t(X), X) gives
    !   dP_a = gamma_a + gamma_t dt_a,
    !   d2P_ab = gamma_ta dt_b + gamma_tb dt_a + gamma_tt dt_a dt_b + gamma_t d2t_ab.
    ! Leaves: f and f_t (Newton on t), P with dP/dX
    ! (layout (c, l) -> c + 2 l) and the contraction lam . d2P/dX dX (upper
    ! triangle, column major). Proved: the first and second total derivatives
    ! of f(t(X), X) vanish, i.e. the formulas are the implicit derivatives.
    use fortsym_expr, only: expr_t, sym, num, operator(+), operator(-), &
                            operator(*), operator(/)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(engine_result_t) :: check
    type(expr_t) :: t, tau(2), o(2), lam(2), basis(0:3), gam(2), f, ft, ftt
    type(expr_t), allocatable :: x(:), dt(:), fa(:), fta(:), d2t(:, :), p(:, :)
    type(expr_t), allocatable :: dp(:), hess(:), roots(:)
    character(8), allocatable :: args(:), names(:)
    character(1) :: suffix
    integer :: order, n, a, b, c, l, k, j
    engine = make_native_engine()
    call w%open('gen_fb_spine', 'src/generated/milca_fb_spine_leaves.f90')
    call w%line('! Generated by gen/gen_fb_spine.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Spine intersection P = gamma(t), tau.(gamma(t) - o) = 0, on the')
    call w%line('! Catmull-Rom segment of chain nodes x_cl; implicit derivatives in x.')
    call w%line('module milca_fb_spine_leaves')
    call w%line('implicit none')
    call w%line('contains')
    t = sym('t')
    tau = [sym('tau1'), sym('tau2')]; o = [sym('o1'), sym('o2')]
    lam = [sym('lam1'), sym('lam2')]
    order = 3
    block
        suffix = 'c'
        n = 2*(order + 1)
        if (allocated(x)) deallocate (x, dt, fa, fta, d2t, p, dp, hess, args, names)
        allocate (x(n), dt(n), fa(n), fta(n), d2t(n, n), p(2, n), dp(2*n), &
                  hess(n*(n + 1)/2), args(n + 7), names(n*(n + 1)/2))
        do l = 0, order
            do c = 1, 2
                write (args(c + 2*l), '(a,i1,i1)') 'x', c, l
                x(c + 2*l) = sym(trim(args(c + 2*l)))
            end do
        end do
        basis(0) = (num(0) - t*t*t + 2*t*t - t)/2
        basis(1) = (3*t*t*t - 5*t*t + 2)/2
        basis(2) = (num(0) - 3*t*t*t + 4*t*t + t)/2
        basis(3) = (t*t*t - t*t)/2
        call prove(basis(0) + basis(1) + basis(2) + basis(3) - 1, 'partition of unity')
        gam = [num(0), num(0)]
        do l = 0, order
            do c = 1, 2
                gam(c) = gam(c) + basis(l)*x(c + 2*l)
            end do
        end do
        f = tau(1)*(gam(1) - o(1)) + tau(2)*(gam(2) - o(2))
        ft = diff(f, t); ftt = diff(ft, t)
        do a = 1, n
            fa(a) = diff(f, x(a)); fta(a) = diff(ft, x(a))
            dt(a) = (num(0) - fa(a))/ft
        end do
        do b = 1, n
            do a = 1, n
                d2t(a, b) = (num(0) - (ftt*dt(a)*dt(b) + fta(a)*dt(b) + fta(b)*dt(a)))/ft
            end do
        end do
        ! The total derivatives of f(t(X), X) vanish: f_t dt_a + f_a = 0 and
        ! f_tt dt_a dt_b + f_ta dt_b + f_tb dt_a + f_t d2t_ab = 0 (f_ab = 0).
        do a = 1, n
            call prove(ft*dt(a) + fa(a), 'first implicit derivative')
            call prove(diff(fa(a), x(min(a + 1, n))), 'f linear in x')
        end do
        call prove(ftt*dt(1)*dt(n) + fta(1)*dt(n) + fta(n)*dt(1) + ft*d2t(1, n), &
                   'second implicit derivative')
        do a = 1, n
            do c = 1, 2
                p(c, a) = diff(gam(c), x(a)) + diff(gam(c), t)*dt(a)
                dp(c + 2*(a - 1)) = p(c, a)
            end do
        end do
        k = 0
        do b = 1, n
            do a = 1, b
                k = k + 1
                write (names(k), '(a,i0,a,i0)') 'h', a, '_', b
                hess(k) = num(0)
                do c = 1, 2
                    hess(k) = hess(k) + lam(c)*(diff(diff(gam(c), t), x(a))*dt(b) &
                        + diff(diff(gam(c), t), x(b))*dt(a) &
                        + diff(diff(gam(c), t), t)*dt(a)*dt(b) &
                        + diff(gam(c), t)*d2t(a, b))
                end do
            end do
        end do
        args(n + 1:n + 7) = [character(8) :: 't', 'tau1', 'tau2', 'o1', 'o2', 'lam1', 'lam2']
        call w%emit('fb_spine_residual', args(:n + 5), &
                    [character(8) :: 'f', 'ft'], [f, ft])
        roots = [gam(1), gam(2), dp]
        call w%emit('fb_spine_point', args(:n + 3), &
                    [character(8) :: 'p1', 'p2', (dname(j), j=1, 2*n)], roots)
        call w%emit('fb_spine_hessian', &
                    [character(8) :: args(:n + 3), 'lam1', 'lam2'], names, hess)
    end block
    call w%line('end module milca_fb_spine_leaves')
    call w%close()
contains
    character(8) function dname(j)
        integer, intent(in) :: j
        write (dname, '(a,i0)') 'd', j
    end function
    subroutine prove(expression, what)
        type(expr_t), intent(in) :: expression
        character(*), intent(in) :: what
        check = engine%zero_test(expression)
        if (check%verdict /= VERDICT_TRUE) then
            write (*, '(a)') 'unproved: '//what
            error stop 1
        end if
    end subroutine
end program gen_fb_spine
