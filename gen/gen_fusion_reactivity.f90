program gen_fusion_reactivity
    ! Fusion S factors and reactivity fits (N3 of docs/nuclear-reactions.md):
    ! the Pade S factor and the Maxwellian reactivity parameterization of
    ! Bosch and Hale (Nucl. Fusion 32, 611, 1992, Tables IV and VII), and the
    ! three-piece p-11B S factor of Wang, Li, Wu and Cui (arXiv:2601.00241,
    ! 2026, Eqs. (3)-(5), Table I). E is the centre-of-mass energy in keV,
    ! T the ion temperature in keV.
    use, intrinsic :: iso_fortran_env, only: int64
    use fortsym_expr, only: expr_t, sym, rat, exp, sqrt, operator(+), operator(-), operator(*), &
                            operator(/), operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: e, t, a(5), b(4), c(7), bg, mrc2, theta, xi, x, s3
    integer :: k
    ! Wang et al. 2026, Table I, converted to keV and MeV b
    real, parameter :: ek(0:4) = [622.2, 1388.4, 2492.4, 3528.6, 4703.6]
    real, parameter :: dek(0:4) = [99.6, 449.9, 238.6, 398.5, 152.5]
    character(len=8), parameter :: ak(0:4) = ['2.0235e6', '4.0102e6', '1.3220e6', &
        '4.9451e6', '4.3430e5']

    e = sym('e'); t = sym('t')
    do k = 1, 5
        a(k) = sym('a'//char(48 + k))
    end do
    do k = 1, 4
        b(k) = sym('b'//char(48 + k))
    end do
    do k = 1, 7
        c(k) = sym('c'//char(48 + k))
    end do
    bg = sym('bg'); mrc2 = sym('mrc2')

    call w%open('gen_fusion_reactivity', 'src/generated/milca_fusion_reactivity_leaves.f90')
    call w%line('! Generated by gen/gen_fusion_reactivity.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! E centre-of-mass energy and T ion temperature in keV.')
    call w%line('module milca_fusion_reactivity_leaves')
    call w%line('implicit none')
    call w%line('contains')
    ! Bosch-Hale Pade S factor, S in keV mb (Table IV)
    call w%emit('bosch_hale_s', ['e ', 'a1', 'a2', 'a3', 'a4', 'a5', 'b1', 'b2', 'b3', 'b4'], &
        ['s'], [(a(1) + e*(a(2) + e*(a(3) + e*(a(4) + e*a(5)))))/ &
        (1 + e*(b(1) + e*(b(2) + e*(b(3) + e*b(4)))))])
    ! Bosch-Hale reactivity in cm^3/s (Table VII, Eqs. (12)-(14))
    theta = t/(1 - t*(c(2) + t*(c(4) + t*c(6)))/(1 + t*(c(3) + t*(c(5) + t*c(7)))))
    xi = (bg**2/(4*theta))**rat(1_int64, 3_int64)
    call w%emit('bosch_hale_reactivity', ['t   ', 'c1  ', 'c2  ', 'c3  ', 'c4  ', 'c5  ', &
        'c6  ', 'c7  ', 'bg  ', 'mrc2'], ['sigv'], &
        [c(1)*theta*sqrt(xi/(mrc2*t**3))*exp(-3*xi)])
    ! p-11B S factor in MeV b, E in keV: below 400 keV with the 148 keV
    ! resonance, 400-700 keV polynomial, 700 keV-10 MeV resonance sum
    call w%emit('pb11_s_low', ['e'], ['s'], [197 + num_r('0.240')*e + num_r('2.31e-4')*e**2 + &
        num_r('1.82e4')/((e - 148)**2 + num_r('2.35')**2)])
    x = (e - 400)/100
    call w%emit('pb11_s_mid', ['e'], ['s'], [num_r('330.2') + num_r('102.436')*x - &
        num_r('58.481')*x**2 + num_r('0.0933')*x**5])
    s3 = num_r('0.209689')
    do k = 0, 4
        s3 = s3 + num_r(trim(ak(k)))/((e - num_r(fmt(ek(k))))**2 + num_r(fmt(dek(k)))**2)
    end do
    call w%emit('pb11_s_high', ['e'], ['s'], [s3])
    call w%line('end module milca_fusion_reactivity_leaves')
    call w%close()

contains

    ! a decimal string such as 2.31e-4 as the exact rational 231/10^6
    function num_r(text) result(v)
        character(*), intent(in) :: text
        type(expr_t) :: v
        character(:), allocatable :: mant
        integer(int64) :: digits, scale
        integer :: epos, dpos, expo, i
        epos = scan(text, 'eE')
        expo = 0
        mant = text
        if (epos > 0) then
            read (text(epos + 1:), *) expo
            mant = text(1:epos - 1)
        end if
        dpos = index(mant, '.')
        if (dpos > 0) then
            expo = expo - (len(mant) - dpos)
            mant = mant(1:dpos - 1)//mant(dpos + 1:)
        end if
        read (mant, *) digits
        scale = 1
        do i = 1, abs(expo)
            scale = scale*10
        end do
        if (expo >= 0) then
            v = rat(digits*scale, 1_int64)
        else
            v = rat(digits, scale)
        end if
    end function num_r

    function fmt(r) result(s)
        real, intent(in) :: r
        character(:), allocatable :: s
        character(32) :: buf
        write (buf, '(f0.1)') r
        s = trim(buf)
    end function fmt

end program gen_fusion_reactivity
