program gen_dk_mono
    use fortsym_expr, only: expr_t, sym, num, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: b, b_theta, kappa, k, omega_e, mean_b2, &
        electric_rate, vt, x, row_ratio
    type(expr_t) :: m, t, nud, v, nu, b0, b2, cs, d11, d13, d33, ups2, d11p, d13p, &
        d33p, den

    ! Axisymmetric surface in Boozer angles, B = B0 b(theta), v = 1. The
    ! parallel derivative is b.grad theta d_theta with b.grad theta = kappa b,
    ! kappa = iota B0/(G + iota I); the flux-surface measure is 1/b^2.
    ! With u = I/Omega_0 = 1 the radial drift is
    !   v_d.grad psi = xi b.grad(xi/b) = -k (b_theta/b^2) (1 + xi^2)/2
    ! at fixed lambda, whose Legendre components are 2/3 and 1/3 of the
    ! factor; the parallel electric field drives xi b.
    b = sym('b'); b_theta = sym('b_theta'); kappa = sym('kappa')
    k = kappa*b

    call writer%open('gen_dk_mono', 'src/generated/milca_dk_mono_leaves.f90')
    call writer%line('! Generated by gen/gen_dk_mono.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module milca_dk_mono_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    ! Streaming factor k, mirror factor k d(ln b)/2, the P0 and P2
    ! components of the radial drift, the P1 component of the electric
    ! drive and the flux-surface weight.
    call writer%emit('dk_mono_point', ['b      ', 'b_theta', 'kappa  '], &
        ['stream ', 'mirror ', 'drift0 ', 'drift2 ', 'drive_e', 'weight '], &
        [k, k*b_theta/(2*b), -(2*k*b_theta)/(3*b*b), -(k*b_theta)/(3*b*b), b, 1/(b*b)], ad=.true.)
    ! Incompressible electric drift divided by speed. The Boozer measure
    ! cancels b^2, leaving a constant multiple of the angular derivative.
    omega_e = sym('omega_e'); mean_b2 = sym('mean_b2')
    call writer%emit('dk_mono_exb_point', ['b      ', 'mean_b2', 'omega_e'], &
        ['advection'], [omega_e*b*b/mean_b2], ad=.true.)
    electric_rate = sym('electric_rate'); vt = sym('vt'); x = sym('x')
    row_ratio = sym('row_ratio')
    call writer%emit('dk_surface_electric_scale', &
        ['electric_rate', 'vt           ', 'x            ', 'row_ratio    '], &
        ['row_rate'], [row_ratio*electric_rate/(vt*x)], ad=.true.)
    call local_characteristics()
    call surface_observables()
    ! Sugama and Nishimura, Phys. Plasmas 9, 4637 (2002), Eq. (43): viscosity
    ! and radial-flux coefficients M, N, L of monoenergetic particles (mass m,
    ! temperature t, speed v, deflection frequency nud = nu v) from the
    ! DKES coefficients, which in terms of the coefficients d11, d13, d33 of
    ! this module (radial drift per v^2 c_s, parallel drive xi b) are
    ! D11 = c_s^2 v^3 d11/4, D13 = c_s v^2 b0 d13/2 and
    ! D33 = (v b0^2/nu) (<b^2>/3 - nu d33); c_s is the radial-drift scale,
    ! v_d.grad(psi) = c_s v^2 (radial drift of d11). The bracket
    ! 1 - 3 m nud D33/(2 T K <B^2>) equals 3 nu d33/<b^2> (2 T K = m v^2).
    ! ups2 = <u^2> carries the Pfirsch-Schlueter part B^2 v^2 nud <U^2>/(3
    ! Omega^2) = v^2 nud c_s^2 ups2/3 of L.
    m = sym('m'); t = sym('t'); nud = sym('nud'); v = sym('v'); nu = sym('nu')
    b0 = sym('b0'); b2 = sym('b2'); cs = sym('cs'); d11 = sym('d11')
    d13 = sym('d13'); d33 = sym('d33'); ups2 = sym('ups2')
    d11p = cs*cs*v*v*v*d11/4
    d13p = cs*v*v*b0*d13/2
    d33p = v*b0*b0*(b2/3 - nu*d33)/nu
    den = 3*nu*d33/b2
    call writer%emit('dk_mono_thermal_point', ['m   ', 't   ', 'nud ', 'v   ', 'nu  ', &
        'b0  ', 'b2  ', 'cs  ', 'd11 ', 'd13 ', 'd33 ', 'ups2'], ['vm', 'vn', 'vl'], &
        [m*m*nud*nud*d33p/(t*den), m*nud*d13p/(t*den), &
        (d11p - v*v*nud*cs*cs*ups2/3 + 3*nud*d13p*d13p/(v*v*b0*b0*b2*den))/t], ad=.true.)
    call writer%line('end module milca_dk_mono_leaves')
    call writer%close()
contains
    subroutine local_characteristics()
        type(expr_t) :: field, b_par, b_perp, pitch, speed, k, er, q, ig
        type(expr_t) :: stream, advection, xdot, xidot, bdot, moment, moment_rate, jacobian, divergence

        field = sym('b'); b_par = sym('b_parallel'); b_perp = sym('b_perp')
        pitch = sym('xi'); speed = sym('x'); k = sym('kappa')
        er = sym('electric'); q = sym('q'); ig = sym('i_over_g')
        stream = speed*pitch*k*field
        advection = er*b_perp/(2*field)
        xdot = advection*speed*(1+pitch**2)
        xidot = -speed*k*(1-pitch**2)*b_par/2+advection*pitch*(1-pitch**2)
        bdot = stream*b_par+er*b_perp
        moment = speed**2*(1-pitch**2)/field
        jacobian = speed**2/field**2
        divergence = diff(jacobian*stream, field)*b_par+diff(jacobian*er, field)*b_perp &
            +diff(jacobian*xdot, speed)+diff(jacobian*xidot, pitch)
        moment_rate = diff(moment, speed)*xdot+diff(moment, pitch)*xidot+diff(moment, field)*bdot
        call exact_zero(moment_rate)
        call exact_zero(divergence)
        call writer%emit('dk_local_characteristic', &
            ['b         ', 'b_parallel', 'b_perp    ', 'xi        ', 'x         ', &
             'kappa     ', 'electric  ', 'q         ', 'i_over_g  '], &
            ['theta_dot  ', 'zeta_dot   ', 'x_dot      ', 'xi_dot     ', 'maxwell_dot'], &
            [stream+er, q*stream-ig*er, xdot, xidot, -2*speed*xdot], ad=.true.)
    end subroutine local_characteristics

    subroutine surface_observables()
        type(expr_t) :: q, ig, density, temperature, elementary, z, phi_prime, &
            e_parallel, ln_n_prime, ln_t_prime, f1, f2, f3, scale, &
            d(3, 3), particle, energy, flow, charge, gamma
        integer :: i, j
        character(3) :: name
        call verify_surface_moments()
        q = sym('q'); ig = sym('i_over_g'); density = sym('density')
        temperature = sym('temperature'); elementary = sym('elementary'); z = sym('z')
        phi_prime = sym('phi_prime'); e_parallel = sym('e_parallel')
        ln_n_prime = sym('ln_n_prime'); ln_t_prime = sym('ln_t_prime')
        charge = z*elementary
        call writer%emit('dk_surface_force_point', &
            [character(11) :: 'ln_n_prime', 'ln_t_prime', 'phi_prime', 'e_parallel', &
            'z', 'elementary', 'temperature'], &
            [character(2) :: 'f1', 'f2', 'f3'], &
            [ln_n_prime+charge*phi_prime/temperature-3*ln_t_prime/2, &
            ln_t_prime, charge*e_parallel/temperature], ad=.true.)
        do j = 1, 3
            do i = 1, 3
                write (name, '(a,i1,i1)') 'd', i, j
                d(i, j) = sym(name)
            end do
        end do
        f1 = sym('f1'); f2 = sym('f2'); f3 = sym('f3')
        scale = q/(1+ig/q)
        particle = -2*density*scale*(scale*(d(1, 1)*f1+d(1, 2)*f2)+d(1, 3)*f3)
        energy = -2*density*temperature*scale &
            *(scale*(d(2, 1)*f1+d(2, 2)*f2)+d(2, 3)*f3)
        flow = 2*(scale*(d(3, 1)*f1+d(3, 2)*f2)+d(3, 3)*f3)
        call writer%emit('dk_surface_flux_point', &
            [character(11) :: 'q', 'i_over_g', 'density', 'temperature', &
            'd11', 'd21', 'd31', 'd12', 'd22', 'd32', 'd13', 'd23', 'd33', 'f1', 'f2', 'f3'], &
            [character(8) :: 'particle', 'energy', 'flow'], [particle, energy, flow], ad=.true.)
        gamma = sym('particle')
        call writer%emit('dk_surface_torque_point', &
            [character(10) :: 'particle', 'q', 'z', 'elementary'], &
            [character(7) :: 'current', 'torque'], [charge*gamma, charge*gamma/q], ad=.true.)
    end subroutine surface_observables

    subroutine verify_surface_moments()
        type(expr_t) :: pitch, one, integrand, value, expected
        integer :: kind
        pitch = sym('xi'); one = num(1)
        do kind = 1, 3
            select case (kind)
            case (1)
                integrand = 1+pitch**2
                expected = 8*one/3
            case (2)
                integrand = (1+pitch**2)*(3*pitch**2-1)/2
                expected = 4*one/15
            case (3)
                integrand = pitch**2
                expected = 2*one/3
            end select
            value = diff(pitch_primitive(kind, pitch), pitch)-integrand
            call exact_zero(value)
            value = pitch_primitive(kind, one)-pitch_primitive(kind, -one)-expected
            call exact_zero(value)
        end do
    end subroutine verify_surface_moments

    function pitch_primitive(kind, pitch) result(value)
        integer, intent(in) :: kind
        type(expr_t), intent(in) :: pitch
        type(expr_t) :: value
        select case (kind)
        case (1); value = pitch+pitch**3/3
        case (2); value = 3*pitch**5/10+pitch**3/3-pitch/2
        case (3); value = pitch**3/3
        end select
    end function pitch_primitive

    subroutine exact_zero(expression)
        type(expr_t), intent(in) :: expression
        type(engine_result_t) :: result
        result = writer%engine%expand(expression)
        if (.not. result%ok) error stop 'surface moment expansion'
        result = writer%engine%simplify(result%value)
        if (.not. result%ok) error stop 'surface moment simplification'
        result = writer%engine%zero_test(result%value)
        if (result%verdict /= VERDICT_TRUE) error stop 'surface moment identity'
    end subroutine exact_zero
end program gen_dk_mono
