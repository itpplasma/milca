program gen_beliaev_budker
    ! The relativistic Landau (Beliaev-Budker) collision kernel in the form of
    ! Braams and Karney (Phys. Rev. Lett. 59, 1817, 1987),
    !   U^ij(u,u') = r^2/(gamma gamma' w^3) [w^2 delta^ij - u^i u^j - u'^i u'^j
    !                + r (u^i u'^j + u'^i u^j)],
    ! r = gamma gamma' - u.u', w^2 = r^2 - 1, momenta u = p/(m c), and the
    ! test-particle coefficients on a cold background (f' = delta(u')),
    ! D^ij = U^ij(u,0)/2 and A^i = -(1/2) d U^ij/d u'_j at u' = 0, per Gamma n.
    use fortsym, only: expr_t, sym, num, sqrt, diff, subs, engine_result_t, &
        operator(+), operator(-), operator(*), operator(/), operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: u(3), v(3), gu, gv, r, w2, kernel(3, 3), cold_d(6), cold_a(3), full(6)
    type(expr_t) :: zero, s
    type(engine_result_t) :: res
    integer :: i, j, k

    u = [sym('ux'), sym('uy'), sym('uz')]
    v = [sym('vx'), sym('vy'), sym('vz')]
    zero = num(0)
    gu = sqrt(1 + u(1)**2 + u(2)**2 + u(3)**2)
    gv = sqrt(1 + v(1)**2 + v(2)**2 + v(3)**2)
    r = gu*gv - (u(1)*v(1) + u(2)*v(2) + u(3)*v(3))
    w2 = r**2 - 1
    do j = 1, 3
        do i = 1, 3
            kernel(i, j) = r**2/(gu*gv*w2*sqrt(w2))*(merge_one(i, j)*w2 - u(i)*u(j) - &
                v(i)*v(j) + r*(u(i)*v(j) + v(i)*u(j)))
        end do
    end do
    k = 0
    do j = 1, 3
        do i = 1, j
            k = k + 1
            full(k) = kernel(i, j)
            cold_d(k) = at_rest(kernel(i, j))/2
        end do
    end do
    do i = 1, 3
        s = zero
        do j = 1, 3
            res = diff(kernel(i, j), v(j))
            if (.not. res%ok) error stop 'gen_beliaev_budker: derivative refused'
            s = s + res%value
        end do
        cold_a(i) = -at_rest(s)/2
    end do

    call w%open('gen_beliaev_budker', 'src/generated/milca_beliaev_budker_leaves.f90')
    call w%line('! Generated by gen/gen_beliaev_budker.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! u = p/(m c); kernel components 11, 12, 22, 13, 23, 33.')
    call w%line('module milca_beliaev_budker_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('bb_kernel', ['ux', 'uy', 'uz', 'vx', 'vy', 'vz'], &
        ['k11', 'k12', 'k22', 'k13', 'k23', 'k33'], full)
    call w%emit('bb_cold', ['ux', 'uy', 'uz'], &
        ['d11', 'd12', 'd22', 'd13', 'd23', 'd33', 'ax ', 'ay ', 'az '], [cold_d, cold_a])
    call w%line('end module milca_beliaev_budker_leaves')
    call w%close()

contains

    function merge_one(i, j) result(e)
        integer, intent(in) :: i, j
        type(expr_t) :: e
        e = num(0)
        if (i == j) e = num(1)
    end function merge_one

    ! the expression at u' = 0
    function at_rest(e) result(out)
        type(expr_t), intent(in) :: e
        type(expr_t) :: out
        type(engine_result_t) :: sub
        integer :: m
        out = e
        do m = 1, 3
            sub = subs(out, v(m), zero)
            if (.not. sub%ok) error stop 'gen_beliaev_budker: substitution refused'
            out = sub%value
        end do
    end function at_rest

end program gen_beliaev_budker
