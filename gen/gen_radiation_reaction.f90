program gen_radiation_reaction
    ! Classical radiation reaction (Q3 of docs/qed-radiation.md): the
    ! Landau-Lifshitz force in uniform fields and its gyro-average in a
    ! uniform magnetic field, the synchrotron friction of the kinetic models.
    ! Units: u = p/(m c), time 1/omega, fields in m c omega/e, kappa =
    ! 2 r_e omega/(3 c). The field-derivative terms of Landau and Lifshitz
    ! (Classical Theory of Fields, section 76) vanish for uniform fields.
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), operator(*), &
                            operator(/), operator(**)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: u(3), e(3), b(3), beta(3), gam, kappa, lorentz(3), force(3), ve(3)
    type(expr_t) :: vxb(3), exb(3), bxbxv(3), power, p, xi, nu
    integer :: i

    u = [sym('ux'), sym('uy'), sym('uz')]
    e = [sym('ex'), sym('ey'), sym('ez')]
    b = [sym('bx'), sym('by'), sym('bz')]
    kappa = sym('kappa')
    gam = sqrt(1 + u(1)**2 + u(2)**2 + u(3)**2)
    do i = 1, 3
        beta(i) = u(i)/gam
    end do
    vxb = cross(beta, b)
    exb = cross(e, b)
    bxbxv = cross(b, cross(b, beta))
    ve(1) = e(1) + vxb(1)
    ve(2) = e(2) + vxb(2)
    ve(3) = e(3) + vxb(3)
    ! (E + beta x B)^2 - (E . beta)^2
    power = ve(1)**2 + ve(2)**2 + ve(3)**2 - (e(1)*beta(1) + e(2)*beta(2) + e(3)*beta(3))**2
    do i = 1, 3
        lorentz(i) = ve(i)
        force(i) = ve(i) + kappa*(exb(i) + bxbxv(i) + &
            e(i)*(e(1)*beta(1) + e(2)*beta(2) + e(3)*beta(3)) - gam**2*beta(i)*power)
    end do
    p = sym('p'); xi = sym('xi'); nu = sym('nu')

    call w%open('gen_radiation_reaction', 'src/generated/milca_radiation_reaction_leaves.f90')
    call w%line('! Generated by gen/gen_radiation_reaction.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! u = p/(m c), time 1/omega, E and B in m c omega/e, kappa = 2 r_e omega/(3c).')
    call w%line('module milca_radiation_reaction_leaves')
    call w%line('implicit none')
    call w%line('contains')
    ! du/dt of a charge -e reversed in sign by the caller's field convention:
    ! the leaf is for charge +e; an electron passes -E and -B
    call w%emit('lorentz_force', ['ux', 'uy', 'uz', 'ex', 'ey', 'ez', 'bx', 'by', 'bz'], &
        ['fx', 'fy', 'fz'], lorentz, ad=.true.)
    call w%emit('landau_lifshitz_force', ['ux   ', 'uy   ', 'uz   ', 'ex   ', 'ey   ', 'ez   ', &
        'bx   ', 'by   ', 'bz   ', 'kappa'], ['fx', 'fy', 'fz'], force, ad=.true.)
    ! gyro-average in a uniform field: dp/dt and dxi/dt with nu = kappa B^2,
    ! xi the cosine of the pitch angle
    gam = sqrt(1 + p**2)
    call w%emit('synchrotron_friction', ['p ', 'xi', 'nu'], ['pdot ', 'xidot'], &
        [-nu*gam*p*(1 - xi**2), nu*xi*(1 - xi**2)/gam], ad=.true.)
    call w%line('end module milca_radiation_reaction_leaves')
    call w%close()

contains

    function cross(a, c) result(r)
        type(expr_t), intent(in) :: a(3), c(3)
        type(expr_t) :: r(3)
        r(1) = a(2)*c(3) - a(3)*c(2)
        r(2) = a(3)*c(1) - a(1)*c(3)
        r(3) = a(1)*c(2) - a(2)*c(1)
    end function cross

end program gen_radiation_reaction
