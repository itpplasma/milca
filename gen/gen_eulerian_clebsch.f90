program gen_eulerian_clebsch
    ! Axisymmetric energy density of the direct Clebsch representation
    ! (docs/eulerian-label-plan.md, (2)-(5)), per unit dR dZ dphi:
    !
    !   A = g grad chi + F(chi) grad theta + G(chi) grad phi,
    !   B_phi = g_Z chi_R - g_R chi_Z - F'(chi) (chi_R theta_Z - chi_Z theta_R),
    !   B_pol = G'(chi) (-chi_Z, chi_R)/R          (e_R x e_Z = -e_phi),
    !   w = R (B_phi^2 + |B_pol|^2)/2 - R p(chi).
    !
    ! Variables u = (chi, chi_R, chi_Z, g_R, g_Z). The profiles enter through
    ! their values at chi: fp = F', gp = G', pres = p and their chi
    ! derivatives (fpp, fppp, gpp, gppp, pp, ppp), so d/dchi is the chain
    ! rule below. Outputs: w, its gradient in u and the upper triangle of the
    ! Hessian.
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(engine_result_t) :: proof
    type(expr_t) :: r, c, cr, cz, gr, gz, tr, tz, fp, fpp, fppp, gp, gpp, gppp, &
        pres, pp, ppp, bphi, bpol2, density
    type(expr_t) :: u(5), gradient(5), hessian(15), cp, gp3, v(7)
    character(4), parameter :: unames(5) = ['c   ', 'c_r ', 'c_z ', 'g_r ', 'g_z ']
    character(16) :: gnames(5), hnames(15)
    integer :: i, j, k

    r = sym('r'); c = sym('c'); cr = sym('c_r'); cz = sym('c_z')
    gr = sym('g_r'); gz = sym('g_z'); tr = sym('t_r'); tz = sym('t_z')
    fp = sym('fp'); fpp = sym('fpp'); fppp = sym('fppp')
    gp = sym('gp'); gpp = sym('gpp'); gppp = sym('gppp')
    pres = sym('pres'); pp = sym('pp'); ppp = sym('ppp')
    u = [c, cr, cz, gr, gz]
    bphi = gz*cr - gr*cz - fp*(cr*tz - cz*tr)
    bpol2 = gp**2*(cr**2 + cz**2)/r**2
    density = r*(bphi**2 + bpol2)/2 - r*pres
    engine = make_native_engine()
    ! B is tangent to the level sets of chi: B_pol . grad chi = 0
    proof = engine%zero_test(gp*(-cz*cr + cr*cz)/r)
    if (proof%verdict /= VERDICT_TRUE) error stop 'tangency unproved'
    do i = 1, 5
        gradient(i) = derivative(density, i)
        gnames(i) = 'w_'//trim(unames(i))
    end do
    ! the g gradient is the toroidal field times the rotated label gradient
    proof = engine%zero_test(gradient(4) + r*bphi*cz)
    if (proof%verdict /= VERDICT_TRUE) error stop 'g gradient unproved'
    proof = engine%zero_test(gradient(5) - r*bphi*cr)
    if (proof%verdict /= VERDICT_TRUE) error stop 'g gradient unproved'
    k = 0
    do i = 1, 5
        do j = i, 5
            k = k + 1
            hessian(k) = derivative(gradient(i), j)
            hnames(k) = 'h_'//trim(unames(i))//'_'//trim(unames(j))
        end do
    end do
    ! the Hessian is symmetric: the mixed derivatives agree in both orders
    proof = engine%zero_test(derivative(gradient(1), 2) - derivative(gradient(2), 1))
    if (proof%verdict /= VERDICT_TRUE) error stop 'Hessian symmetry unproved'
    call w%open('gen_eulerian_clebsch', 'src/generated/milca_eulerian_clebsch_leaves.f90')
    call w%line('! Generated by gen/gen_eulerian_clebsch.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module milca_eulerian_clebsch_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('clebsch_energy_axisym', &
        ['r   ', 'c   ', 'c_r ', 'c_z ', 'g_r ', 'g_z ', 't_r ', 't_z ', 'fp  ', 'fpp ', &
        'fppp', 'gp  ', 'gpp ', 'gppp', 'pres', 'pp  ', 'ppp '], &
        ['w               ', gnames, hnames], [density, gradient, hessian])
    call emit_3d()
    call w%line('end module milca_eulerian_clebsch_leaves')
    call w%close()
    print '(a)', '[V] FortSym tangency (2D, 3D), g gradient, Hessian symmetry and the 3D reduction proved; Clebsch leaves generated'

contains

    subroutine emit_3d()
        !! 3D density per unit dR dphi dZ in physical cylindrical components
        !! (R, phi, Z), right-handed: a x b = (a_p b_z - a_z b_p, a_z b_r -
        !! a_r b_z, a_r b_p - a_p b_r). grad phi = (0, 1/R, 0), h = h_theta
        !! (the winding form about the axis curve) given as a vector.
        !! Variables v = (chi, chi_r, chi_p, chi_z, g_r, g_p, g_z).
        type(expr_t) :: h(3), gc(3), gg(3), gphi(3), b(3), dens, c1(3), c2(3), c3(3)
        type(expr_t) :: grad7(7), hess7(28)
        character(4), parameter :: vnames(7) = ['c   ', 'c_r ', 'c_p ', 'c_z ', 'g_r ', &
                                                'g_p ', 'g_z ']
        character(16) :: g7(7), h7(28)
        integer :: a, b2, m

        cp = sym('c_p'); gp3 = sym('g_p')
        gc = [cr, cp, cz]
        gg = [gr, gp3, gz]
        h = [sym('h_r'), sym('h_p'), sym('h_z')]
        gphi = [0*r, 1/r, 0*r]
        c1 = cross(gg, gc)
        c2 = cross(gc, h)
        c3 = cross(gc, gphi)
        do a = 1, 3
            b(a) = c1(a) + fp*c2(a) + gp*c3(a)
        end do
        dens = r*(b(1)**2 + b(2)**2 + b(3)**2)/2 - r*pres
        ! tangency in 3D: B . grad chi = 0 identically
        proof = engine%zero_test(b(1)*gc(1) + b(2)*gc(2) + b(3)*gc(3))
        if (proof%verdict /= VERDICT_TRUE) error stop '3D tangency unproved'
        ! the axisymmetric density is the 3D one with chi_p = g_p = 0, h_p = 0
        proof = engine%zero_test(subs3(dens) - density)
        if (proof%verdict /= VERDICT_TRUE) error stop '3D reduction unproved'
        v = [c, cr, cp, cz, gr, gp3, gz]
        do a = 1, 7
            grad7(a) = deriv7(dens, a)
            g7(a) = 'w_'//trim(vnames(a))
        end do
        m = 0
        do a = 1, 7
            do b2 = a, 7
                m = m + 1
                hess7(m) = deriv7(grad7(a), b2)
                h7(m) = 'h_'//trim(vnames(a))//'_'//trim(vnames(b2))
            end do
        end do
        call w%emit('clebsch_energy_3d', &
            ['r   ', 'c   ', 'c_r ', 'c_p ', 'c_z ', 'g_r ', 'g_p ', 'g_z ', 'h_r ', 'h_p ', &
            'h_z ', 'fp  ', 'fpp ', 'fppp', 'gp  ', 'gpp ', 'gppp', 'pres', 'pp  ', 'ppp '], &
            ['w               ', g7, h7], [dens, grad7, hess7])

    end subroutine emit_3d

    function cross(x, y) result(z)
        type(expr_t), intent(in) :: x(3), y(3)
        type(expr_t) :: z(3)

        z = [x(2)*y(3) - x(3)*y(2), x(3)*y(1) - x(1)*y(3), x(1)*y(2) - x(2)*y(1)]
    end function cross

    function subs3(e) result(f)
        type(expr_t), intent(in) :: e
        type(expr_t) :: f

        f = subs(subs(subs(subs(subs(e, cp, 0*r), gp3, 0*r), sym('h_p'), 0*r), &
                      sym('h_r'), tr), sym('h_z'), tz)
    end function subs3

    function deriv7(e, i) result(d)
        type(expr_t), intent(in) :: e
        integer, intent(in) :: i
        type(expr_t) :: d

        d = diff(e, v(i))
        if (i == 1) d = d + diff(e, fp)*fpp + diff(e, fpp)*fppp + diff(e, gp)*gpp &
                        + diff(e, gpp)*gppp + diff(e, pres)*pp + diff(e, pp)*ppp
    end function deriv7

    function derivative(e, i) result(d)
        !! d e/d u_i, with chi entering also through the profile values.
        type(expr_t), intent(in) :: e
        integer, intent(in) :: i
        type(expr_t) :: d

        d = diff(e, u(i))
        if (i == 1) d = d + diff(e, fp)*fpp + diff(e, fpp)*fppp + diff(e, gp)*gpp &
                        + diff(e, gpp)*gppp + diff(e, pres)*pp + diff(e, pp)*ppp
    end function derivative

end program gen_eulerian_clebsch
