program gen_toroidal_momentum
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*)
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: old, dt, inner, outer, torque

    old = sym('old')
    dt = sym('dt')
    inner = sym('inner')
    outer = sym('outer')
    torque = sym('torque')

    call writer%open('gen_toroidal_momentum', &
        'src/generated/milca_toroidal_momentum_leaves.f90')
    call writer%line('! Generated by gen/gen_toroidal_momentum.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%line('module milca_toroidal_momentum_leaves')
    call writer%line('implicit none')
    call writer%line('contains')
    ! A small source must survive subtraction of a large common face flux.
    call writer%emit('momentum_shell', ['old   ', 'dt    ', 'inner ', 'outer ', 'torque'], &
        ['next'], [old + dt*(torque - (outer - inner))], ad=.true., interval=.true.)
    call writer%line('end module milca_toroidal_momentum_leaves')
    call writer%close()
end program gen_toroidal_momentum
