program gen_flux_map
    ! Pointwise kernels of the Cartesian flux map (docs/flux-map.md),
    ! axisymmetric, per unit dR dZ:
    !
    !   u = (x, y): section -> unit disc,  s = x^2 + y^2,
    !   B_phi = tau(s) (x_R y_Z - x_Z y_R),           tau = Phi'(s)/pi,
    !   B_pol = psi'(s) (-s_Z, s_R)/R,                grad s = 2 (x grad x + y grad y),
    !   W = int [B_phi^2/2 + |B_pol|^2/2 - p(s)] R dR dZ.
    !
    ! Two leaves, so that B_phi can enter the energy pointwise or projected:
    ! flux_map_toroidal returns c = B_phi, flux_map_poloidal returns
    ! w = R |B_pol|^2/2 - R p. Variables v = (x, y, x_R, x_Z, y_R, y_Z). The
    ! profiles enter through their values at s (tau, gp = psi', pres = p)
    ! and their s derivatives, so d/dv is the chain rule below with
    ! ds/dx = 2 x, ds/dy = 2 y. Outputs: the value, its gradient in v and the
    ! upper triangle of the Hessian.
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*), &
        operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_engine, only: engine_result_t, VERDICT_TRUE
    use fortsym_engine_native, only: native_engine_t, make_native_engine
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(native_engine_t) :: engine
    type(engine_result_t) :: proof
    type(expr_t) :: r, x, y, xr, xz, yr, yz, tau, taup, taupp, gp, gpp, gppp, pres, pp, ppp
    type(expr_t) :: v(6), rot(6), c, dens, sr, sz, grad(6), hess(21), turn
    character(4), parameter :: vnames(6) = ['x   ', 'y   ', 'x_r ', 'x_z ', 'y_r ', 'y_z ']
    character(16) :: gnames(6), hnames(21)
    integer :: i, j, k
    logical :: toroidal

    r = sym('r'); x = sym('x'); y = sym('y')
    xr = sym('x_r'); xz = sym('x_z'); yr = sym('y_r'); yz = sym('y_z')
    tau = sym('tau'); taup = sym('taup'); taupp = sym('taupp')
    gp = sym('gp'); gpp = sym('gpp'); gppp = sym('gppp')
    pres = sym('pres'); pp = sym('pp'); ppp = sym('ppp')
    v = [x, y, xr, xz, yr, yz]
    ! generator of a rotation of the disc, the gauge theta* -> theta* + const
    rot = [0*x - y, x, 0*x - yr, 0*x - yz, xr, xz]
    engine = make_native_engine()
    call w%open('gen_flux_map', 'src/generated/milca_flux_map_leaves.f90')
    call w%line('! Generated by gen/gen_flux_map.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('module milca_flux_map_leaves')
    call w%line('implicit none')
    call w%line('contains')

    toroidal = .true.
    c = tau*(xr*yz - xz*yr)
    call derivatives(c, 'c')
    call w%emit('flux_map_toroidal', &
        ['x    ', 'y    ', 'x_r  ', 'x_z  ', 'y_r  ', 'y_z  ', 'tau  ', 'taup ', 'taupp'], &
        ['c               ', gnames, hnames], [c, grad, hess])

    toroidal = .false.
    sr = 2*(x*xr + y*yr)
    sz = 2*(x*xz + y*yz)
    ! B_pol is tangent to the level sets of s
    proof = engine%zero_test(gp*(-sz*sr + sr*sz)/r)
    if (proof%verdict /= VERDICT_TRUE) error stop 'tangency unproved'
    dens = gp**2*(sr**2 + sz**2)/(2*r) - r*pres
    call derivatives(dens, 'w')
    call w%emit('flux_map_poloidal', &
        ['r   ', 'x   ', 'y   ', 'x_r ', 'x_z ', 'y_r ', 'y_z ', 'gp  ', 'gpp ', 'gppp', &
        'pres', 'pp  ', 'ppp '], &
        ['w               ', gnames, hnames], [dens, grad, hess])
    call w%line('end module milca_flux_map_leaves')
    call w%close()
    print '(a)', '[V] FortSym tangency, rotation invariance of both kernels and Hessian symmetry proved; flux-map leaves generated'

contains

    subroutine derivatives(e, name)
        !! Gradient and Hessian of e in v with their names; proves that e is
        !! invariant under rotations of the disc and that the Hessian is
        !! symmetric.
        type(expr_t), intent(in) :: e
        character(*), intent(in) :: name

        do i = 1, 6
            grad(i) = derivative(e, i)
            gnames(i) = name//'_'//trim(vnames(i))
        end do
        turn = grad(1)*rot(1)
        do i = 2, 6
            turn = turn + grad(i)*rot(i)
        end do
        proof = engine%zero_test(turn)
        if (proof%verdict /= VERDICT_TRUE) error stop 'rotation invariance unproved'
        k = 0
        do i = 1, 6
            do j = i, 6
                k = k + 1
                hess(k) = derivative(grad(i), j)
                hnames(k) = 'h_'//trim(vnames(i))//'_'//trim(vnames(j))
            end do
        end do
        proof = engine%zero_test(derivative(grad(1), 2) - derivative(grad(2), 1))
        if (proof%verdict /= VERDICT_TRUE) error stop 'Hessian symmetry unproved'
        proof = engine%zero_test(derivative(grad(1), 3) - derivative(grad(3), 1))
        if (proof%verdict /= VERDICT_TRUE) error stop 'Hessian symmetry unproved'
    end subroutine derivatives

    function derivative(e, i) result(d)
        !! d e/d v_i, with s = x^2 + y^2 entering through the profile values.
        type(expr_t), intent(in) :: e
        integer, intent(in) :: i
        type(expr_t) :: d

        d = diff(e, v(i))
        if (i > 2) return
        if (toroidal) then
            d = d + 2*v(i)*(diff(e, tau)*taup + diff(e, taup)*taupp)
        else
            d = d + 2*v(i)*(diff(e, gp)*gpp + diff(e, gpp)*gppp + diff(e, pres)*pp + diff(e, pp)*ppp)
        end if
    end function derivative

end program gen_flux_map
