program gen_sheet_flux
    ! Integrands of the coil fluxes in the cut terms of the 3D sheet-current
    ! vacuum (theory/derivations/free-boundary-plasma-boundary-sheet-3d.md),
    ! with their gradient and Hessian in the boundary inputs (r, z and one
    ! parameter derivative of each) at fixed quadrature parameters:
    !
    !   fan:    s B_phi(P) (dZ r_u - dR z_u),   P = c + s (X - c) at v = 0,
    !   ribbon: B(P) . (P_s x P_v),             P = L + s (X - L) at angle v,
    !
    ! dR = r - c_R (or r - L_R), X the boundary point, L a fixed curve inside
    ! the plasma. B enters by its value, gradient and Hessian in (R, Z) at P,
    ! written as its Taylor polynomial in the displacement s (r - r0, z - z0)
    ! with r0 -> r, z0 -> z after differentiation, so the derivatives through
    ! B(P) are exact. Components (B_R, B_phi, B_Z), cross products in the
    ! right-handed (e_R, e_phi, e_Z).
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), operator(*), &
        operator(/)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs_many
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: x(4), s, cr, cz, hr, hz, b(18), f, pr, prv, pzv, dr, dz
    type(expr_t) :: br, bp, bz
    character(8), parameter :: jets(18) = [character(8) :: 'b_r', 'b_r_r', 'b_r_z', &
        'b_r_rr', 'b_r_rz', 'b_r_zz', 'b_p', 'b_p_r', 'b_p_z', 'b_p_rr', 'b_p_rz', &
        'b_p_zz', 'b_z', 'b_z_r', 'b_z_z', 'b_z_rr', 'b_z_rz', 'b_z_zz']
    integer :: i

    do i = 1, 18
        b(i) = sym(trim(jets(i)))
    end do
    s = sym('s')
    cr = sym('cr')
    cz = sym('cz')
    hr = s*(sym('r') - sym('r0'))
    hz = s*(sym('z') - sym('z0'))
    br = taylor(b(1:6))
    bp = taylor(b(7:12))
    bz = taylor(b(13:18))

    call w%open('gen_sheet_flux', 'src/generated/milca_sheet_flux_leaves.f90')
    call w%line('! Generated by gen/gen_sheet_flux.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Coil-flux integrands of the 3D sheet-current vacuum: value,')
    call w%line('! gradient and upper-triangle Hessian (row-wise) in the boundary inputs.')
    call w%line('module milca_sheet_flux_leaves')
    call w%line('implicit none')
    call w%line('contains')

    ! fan at v = 0: inputs (r, z, r_u, z_u)
    x = [sym('r'), sym('z'), sym('ru'), sym('zu')]
    dr = x(1) - cr
    dz = x(2) - cz
    f = s*bp*(dz*x(3) - dr*x(4))
    call emit_jet('fan_flux_jet', [character(8) :: 'r', 'z', 'ru', 'zu', 's', 'cr', &
        'cz', jets(7:12)], f)

    ! ribbon from L = (cr, cz)(v) with derivatives (crv, czv): inputs (r, z,
    ! r_v, z_v) of the boundary loop
    x = [sym('r'), sym('z'), sym('rv'), sym('zv')]
    dr = x(1) - cr
    dz = x(2) - cz
    pr = cr + s*dr
    prv = sym('crv') + s*(x(3) - sym('crv'))
    pzv = sym('czv') + s*(x(4) - sym('czv'))
    ! P_s = (dR, 0, dZ), P_v = (prv, pr, pzv)
    f = br*(-dz*pr) + bp*(dz*prv - dr*pzv) + bz*(dr*pr)
    call emit_jet('ribbon_flux_jet', [character(8) :: 'r', 'z', 'rv', 'zv', 's', &
        'cr', 'cz', 'crv', 'czv', jets], f)

    call w%line('end module milca_sheet_flux_leaves')
    call w%close()

contains

    function taylor(c) result(t)
        type(expr_t), intent(in) :: c(6)
        type(expr_t) :: t
        t = c(1) + c(2)*hr + c(3)*hz + c(4)*hr*hr/2 + c(5)*hr*hz + c(6)*hz*hz/2
    end function taylor

    subroutine emit_jet(name, args, f)
        character(*), intent(in) :: name
        character(8), intent(in) :: args(:)
        type(expr_t), intent(in) :: f
        type(expr_t) :: roots(15), g(4)
        character(8) :: names(15)
        ! outputs named by input position: r, z, then the two derivatives a, b
        character(2), parameter :: v(4) = [character(2) :: 'r', 'z', 'a', 'b']
        integer :: i, j, k
        roots(1) = f
        names(1) = 'value'
        do i = 1, 4
            g(i) = diff(f, x(i))
            roots(1 + i) = g(i)
            names(1 + i) = 'g_'//v(i)
        end do
        k = 5
        do i = 1, 4
            do j = i, 4
                k = k + 1
                roots(k) = diff(g(i), x(j))
                names(k) = 'h_'//trim(v(i))//trim(v(j))
            end do
        end do
        do k = 1, 15
            roots(k) = subs_many(roots(k), [sym('r0'), sym('z0')], [x(1), x(2)])
        end do
        call w%emit(name, args, names, roots)
    end subroutine emit_jet

end program gen_sheet_flux
