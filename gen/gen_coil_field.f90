program gen_coil_field
    ! Jets of the potential 1/|r| of a point source, r = x - y, for the coil
    ! field of the free boundary (milca_ideal_fb_coil_field): the coil field in
    ! the coil-free region is F grad(phi) + grad(chi) with chi a sum of point
    ! sources outside the region, so B and its first and second derivatives
    ! need the gradient, Hessian and third derivatives of 1/|r|. Leaves: the
    ! value, the 3-gradient, the 6 Hessian entries (xx, xy, xz, yy, yz, zz)
    ! and the 10 third derivatives (xxx, xxy, xxz, xyy, xyz, xzz, yyy, yyz,
    ! yzz, zzz), in one leaf so they share subexpressions.
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(*), &
                            operator(/)
    use fortsym_diff, only: diff
    use milca_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(expr_t) :: r(3), f, g(3), h(6), t(10), roots(20)
    character(8) :: names(20)
    integer :: i, j, k, n
    r = [sym('rx'), sym('ry'), sym('rz')]
    f = 1/sqrt(r(1)*r(1) + r(2)*r(2) + r(3)*r(3))
    do i = 1, 3
        g(i) = diff(f, r(i))
    end do
    n = 0
    do i = 1, 3
        do j = i, 3
            n = n + 1
            h(n) = diff(g(i), r(j))
        end do
    end do
    n = 0
    do i = 1, 3
        do j = i, 3
            do k = j, 3
                n = n + 1
                t(n) = diff(diff(g(i), r(j)), r(k))
            end do
        end do
    end do
    roots = [f, g, h, t]
    names = [character(8) :: 'v', 'gx', 'gy', 'gz', 'hxx', 'hxy', 'hxz', 'hyy', 'hyz', &
        'hzz', 'txxx', 'txxy', 'txxz', 'txyy', 'txyz', 'txzz', 'tyyy', 'tyyz', 'tyzz', &
        'tzzz']
    call w%open('gen_coil_field', 'src/generated/milca_coil_field_leaves.f90')
    call w%line('! Generated by gen/gen_coil_field.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! 1/|r| with its gradient, Hessian (xx, xy, xz, yy, yz, zz) and')
    call w%line('! third derivatives (xxx, xxy, xxz, xyy, xyz, xzz, yyy, yyz, yzz, zzz).')
    call w%line('module milca_coil_field_leaves')
    call w%line('implicit none')
    call w%line('contains')
    call w%emit('point_source_jet', [character(8) :: 'rx', 'ry', 'rz'], names, roots)
    call w%line('end module milca_coil_field_leaves')
    call w%close()
end program gen_coil_field
